-- ezBlog schema (PostgreSQL). All timestamps are TIMESTAMPTZ and hold UTC instants.

CREATE TABLE users (
                       id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name        VARCHAR(100) NOT NULL,
                       email       VARCHAR(254) NOT NULL,
                       password    VARCHAR(100),
                       role        VARCHAR(20)  NOT NULL DEFAULT 'USER',
                       enabled     BOOLEAN      NOT NULL DEFAULT TRUE,
                       bio         TEXT         DEFAULT '',
                       created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       CONSTRAINT chk_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE UNIQUE INDEX uq_users_email_upper ON users (upper(email));

CREATE TABLE email_verifications (
                                     id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     email          VARCHAR(254) NOT NULL UNIQUE,
                                     name           VARCHAR(100) NOT NULL,
                                     password_hash  VARCHAR(100) NOT NULL,
                                     token_hash     VARCHAR(64)  NOT NULL UNIQUE,
                                     expires_at     TIMESTAMPTZ  NOT NULL,
                                     created_at     TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_email_verifications_expires_at ON email_verifications (expires_at);

CREATE TABLE posts (
                       id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       title       VARCHAR(200) NOT NULL,
                       content     TEXT         NOT NULL,
                       excerpt     TEXT,
                       author_id   BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                       category    VARCHAR(50)  NOT NULL,
                       read_time   INTEGER      DEFAULT 5,
                       published   BOOLEAN      DEFAULT TRUE,
                       created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_posts_author_created    ON posts (author_id, created_at DESC);
CREATE INDEX idx_posts_published_created ON posts (created_at DESC) WHERE published = TRUE;
CREATE INDEX idx_posts_category_created  ON posts (category, created_at DESC) WHERE published = TRUE;

CREATE TABLE post_tags (
                           post_id  BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
                           tag      VARCHAR(30) NOT NULL,
                           PRIMARY KEY (post_id, tag)
);